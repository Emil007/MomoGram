// Audio facade: each game's own music (extracted from the
// user's own games), plus MomoGram's own small UI sounds.
import { Sdat } from './audio/sdat';
import { SeqPlayer } from './audio/player';
import { oggInfo } from './audio/fsb5';
import { decodeBcstm, isBcstm } from './audio/bcstm';
import { settings, storage } from './store';
import { ChipPlayer } from './audio/chipplayer';

let ac: AudioContext | null = null;
let master: GainNode | null = null;
let sfxGain: GainNode | null = null;
// sound effects have a context of their own, so pausing the music (suspending its context) keeps them working
let sfxAc: AudioContext | null = null;
let paused = false;
let current = '';
const listeners: Array<(id: string) => void> = [];
const changed = () => { for (const f of [...listeners]) f(current); };
let pending: (() => void) | null = null;
/** bumped on every playPack/stop so a late load does not steal Now Playing */
let playGen = 0;
function flushPending() {
  if (paused || !pending) return;
  const p = pending;
  pending = null;
  p();
}

// pack music: decoded streams are cached (a few per session); sound archives get their own sequencer
const buffers = new Map<string, AudioBuffer>();
const packSeq = new Map<string, SeqPlayer>();
let stream: { src: AudioBufferSourceNode; gain: GainNode } | null = null;
let packSeqPlaying: SeqPlayer | null = null;
// one loudness for every game: steady level of the song, not its peaks, so a hit doesn't turn the rest down
const TARGET_RMS = 0.12;
const songLevel = new Map<string, number>();
let seqTrim = 1, chipTrim = 1;
const bufferLevel = new WeakMap<AudioBuffer, number>();
let meter: AnalyserNode | null = null;
let meterFrom: AudioNode | null = null;
// pack music generated by an emulated Game Boy / Super Famicom sound chip ("file#gb:N", "file#spc:N")
let chip: ChipPlayer | null = null;
const chipData = new Map<string, Uint8Array>();

function ensure(): boolean {
  if (!ac) {
    try {
      ac = new AudioContext();
      // any resume (tab shown, unlock, unpause) must play the track queued while suspended
      ac.onstatechange = () => { if (!paused && ac?.state === 'running') flushPending(); };
    } catch { return false; }
    master = ac.createGain();
    master.gain.value = settings.musicVolume;
    master.connect(ac.destination);
    const an = ac.createAnalyser();
    master.connect(an);
    (window as any).__audioLevel = () => { const b = new Float32Array(an.fftSize); an.getFloatTimeDomainData(b); return Math.sqrt(b.reduce((a, v) => a + v * v, 0) / b.length); };
  }
  if (!sfxAc) {
    try { sfxAc = new AudioContext(); sfxGain = sfxAc.createGain(); sfxGain.gain.value = 0.25; sfxGain.connect(sfxAc.destination); } catch { sfxAc = null; }
  }
  return true;
}

// browsers only allow audio after a user gesture
const unlock = () => {
  if (!ensure()) return;
  // resume() is asynchronous: start the queued track once the context really runs (it was lost before)
  sfxAc?.resume().catch(() => {});
  if (paused) return;
  ac!.resume().then(flushPending).catch(() => {});
};
window.addEventListener('pointerdown', unlock);
// app in the background (other app, locked phone, hidden tab): pause all sound, continue when it comes back
document.addEventListener('visibilitychange', () => {
  if (!ac) return;
  if (document.hidden) { ac.suspend().catch(() => {}); sfxAc?.suspend().catch(() => {}); }
  else { if (!paused) ac.resume().then(flushPending).catch(() => {}); sfxAc?.resume().catch(() => {}); }
});
window.addEventListener('pagehide', () => { ac?.suspend().catch(() => {}); sfxAc?.suspend().catch(() => {}); });
(window as any).__music = () => current;
window.addEventListener('keydown', unlock);

function clampGain(g: number) {
  return Number.isFinite(g) && g > 0 ? Math.max(0.3, Math.min(4, g)) : 1;
}

/** gain that brings a steady level to TARGET_RMS, limited so the peaks still fit */
function gainForRms(rms: number, peak = 0) {
  if (rms < 0.008) return 1;
  let g = TARGET_RMS / rms;
  if (peak > 0.01 && peak * g > 0.95) g = 0.95 / peak;
  return clampGain(g);
}

function levelOf(buf: AudioBuffer): number {
  const cached = bufferLevel.get(buf);
  if (cached !== undefined) return cached;
  const step = Math.max(1, Math.floor(buf.length / 120000));
  let sum = 0, n = 0, peak = 0;
  const chs = buf.numberOfChannels;
  for (let i = 0; i < buf.length; i += step) {
    let v = 0;
    for (let c = 0; c < chs; c++) v += buf.getChannelData(c)[i];
    v /= chs;
    const a = Math.abs(v);
    if (a > peak) peak = a;
    if (a > 0.002) { sum += v * v; n++; }
  }
  const g = n ? gainForRms(Math.sqrt(sum / n), peak) : 1;
  bufferLevel.set(buf, g);
  return g;
}

function listen(node: AudioNode) {
  if (!ac) return;
  if (!meter) { meter = ac.createAnalyser(); meter.fftSize = 2048; meter.smoothingTimeConstant = 0; }
  if (meterFrom && meterFrom !== node) { try { meterFrom.disconnect(meter); } catch { /* not connected */ } }
  if (meterFrom !== node) { node.connect(meter); meterFrom = node; }
}

/** hear a live song and ease it to the same level. `from` is the gain already applied, because the meter hears that. */
function matchLive(id: string, node: AudioNode, from: number, apply: (g: number, ramp: boolean) => void) {
  if (songLevel.has(id)) return;
  listen(node);
  const samples: number[] = [];
  let peak = 0;
  const started = performance.now();
  const tick = () => {
    if (current !== id || !meter) return;
    const b = new Float32Array(meter.fftSize);
    meter.getFloatTimeDomainData(b);
    let sum = 0;
    for (let i = 0; i < b.length; i++) {
      const a = Math.abs(b[i]);
      if (a > peak) peak = a;
      sum += b[i] * b[i];
    }
    const rms = Math.sqrt(sum / b.length);
    if (rms > 0.01) samples.push(rms);
    const elapsed = performance.now() - started;
    if ((samples.length >= 8 && elapsed > 500) || elapsed > 1600) {
      if (!samples.length || current !== id) return;
      samples.sort((a, c) => a - c);
      const base = from > 0.001 ? from : 1;
      const g = gainForRms(samples[Math.floor(samples.length / 2)] / base, peak / base);
      songLevel.set(id, g);
      apply(g, Math.abs(g - from) > 0.05);
      return;
    }
    setTimeout(tick, 60);
  };
  setTimeout(tick, 280);
}

function stopPackMusic(fade = 0.15) {
  if (stream && ac) {
    const s = stream; stream = null;
    try { s.gain.gain.setTargetAtTime(0, ac.currentTime, fade / 3); s.src.stop(ac.currentTime + fade * 2); } catch { /* stopped */ }
  }
  packSeqPlaying?.stop(fade); packSeqPlaying = null;
  chip?.stop(fade);
}

async function loadBuffer(packId: string, name: string): Promise<AudioBuffer | null> {
  const key = packId + '/' + name;
  if (buffers.has(key)) return buffers.get(key)!;
  const data = await storage.loadAsset(packId, name);
  if (!data) return null;
  let buf: AudioBuffer;
  const ogg = oggInfo(data);
  if (ogg) {
    // Ogg Vorbis (Switch music): the browser decodes it; loop points in samples of the original rate
    buf = await ac!.decodeAudioData(data.slice().buffer);
    (buf as any).loopInfo = ogg.loop ? { loop: true, loopStart: ogg.loop[0], loopEnd: ogg.loop[1], sampleRate: ogg.rate } : null;
  } else if (data[0] === 0x52 && data[1] === 0x49 && data[2] === 0x46 && data[3] === 0x46) {
    buf = await ac!.decodeAudioData(data.slice().buffer);
    (buf as any).loopInfo = null;
  } else if (isBcstm(data)) {
    const s = decodeBcstm(data);
    buf = ac!.createBuffer(s.channels.length, s.channels[0].length, s.sampleRate);
    s.channels.forEach((c, i) => buf.copyToChannel(c as Float32Array<ArrayBuffer>, i));
    (buf as any).loopInfo = s;
  } else {
    // MP3 (Android games) and anything else the browser decodes
    try { buf = await ac!.decodeAudioData(data.slice().buffer); } catch { return null; }
    (buf as any).loopInfo = null;
  }
  if (buffers.size > 6) buffers.delete(buffers.keys().next().value!);
  buffers.set(key, buf);
  return buf;
}

export const Audio = {
  /**
   * music from a pack ("Bgm_Home.bcstm", or "sound.sdat#SEQ_NAME" for DS sound archives).
   * Returns false when the pack has no such music (the caller then plays nothing or other music).
   */
  async playPack(packId: string, ref: string | undefined, loop = true): Promise<boolean> {
    if (!ref || !settings.packMusic) return false;
    if (!settings.music) { this.stop(); return true; }
    const id = packId + '/' + ref;
    if (paused && id !== current) Audio.resume();
    if (id === current && (stream || packSeqPlaying?.playing || chip?.playing)) return true;
    // context suspended (hidden tab, not yet unlocked): keep the track and play it when audio actually runs
    if (!ac || ac.state !== 'running') { pending = () => { void Audio.playPack(packId, ref, loop); }; return true; }
    pending = null;
    ensure();
    const gen = ++playGen;
    // load failed and this is still the request: do not leave the previous song playing, and do not name a track that never started
    const failed = (): false => {
      if (gen !== playGen) return false;
      current = '';
      changed();
      stopPackMusic(0.1);
      return false;
    };
    try {
      const [file, seq] = ref.split('#');
      const cm = seq?.match(/^(gb|spc):(\d+)$/);
      if (cm) {
        const key = packId + '/' + file;
        let d = chipData.get(key);
        if (!d) {
          d = await storage.loadAsset(packId, file) ?? undefined;
          if (!d) return failed();
          if (chipData.size > 3) chipData.delete(chipData.keys().next().value!);
          chipData.set(key, d);
        }
        if (gen !== playGen) return false;
        stopPackMusic();
        chip ??= new ChipPlayer(ac!, master!);
        const fromChip = songLevel.get(id) ?? chipTrim;
        chip.setTrim(fromChip);
        const started = await chip.play(cm[1] as 'gb' | 'spc', key, d, +cm[2]);
        if (!started || gen !== playGen) return failed();
        current = id; changed();
        if (!songLevel.has(id)) matchLive(id, chip.monitor, fromChip, (g, ramp) => { chipTrim = g; if (current === id) chip!.setTrim(g, ramp); });
        return true;
      }
      if (seq) {
        let sp = packSeq.get(packId + '/' + file);
        if (!sp) {
          const d = await storage.loadAsset(packId, file);
          if (!d) return failed();
          sp = new SeqPlayer(ac!, master!, new Sdat(d));
          packSeq.set(packId + '/' + file, sp);
        }
        if (gen !== playGen) return false;
        stopPackMusic();
        packSeqPlaying = sp;
        const fromSeq = songLevel.get(id) ?? seqTrim;
        sp.setTrim(fromSeq);
        const started = sp.play(seq, loop);
        if (!started || gen !== playGen) return failed();
        current = id; changed();
        if (!songLevel.has(id)) matchLive(id, sp.monitor, fromSeq, (g, ramp) => { seqTrim = g; if (current === id) sp!.setTrim(g, ramp); });
        return true;
      }
      const buf = await loadBuffer(packId, file);
      if (!buf || buf.length === 0) return failed();
      if (gen !== playGen) return false;
      stopPackMusic();
      const src = ac!.createBufferSource(), gain = ac!.createGain();
      src.buffer = buf;
      gain.gain.value = levelOf(buf);
      const li = (buf as any).loopInfo;
      // a file with loop points repeats between them; other music repeats the whole piece
      if (loop) { src.loop = true; if (li?.loop) { src.loopStart = li.loopStart / li.sampleRate; src.loopEnd = li.loopEnd / li.sampleRate; } }
      src.connect(gain).connect(master!);
      src.start();
      stream = { src, gain };
      src.onended = () => { if (stream?.src === src) stream = null; };
      current = id; changed();
      return true;
    } catch (e) {
      console.warn('pack music', e);
      return failed();
    }
  },
  stop() { playGen++; pending = null; current = ''; if (paused) Audio.resume(); changed(); stopPackMusic(0.1); },
  /** hold the music where it is (the whole music context stops, so every kind of music continues exactly) */
  pause() { if (!ac || paused) return; paused = true; ac.suspend().catch(() => {}); changed(); },
  resume() { if (!paused) return; paused = false; ac?.resume().then(flushPending).catch(() => {}); changed(); },
  paused: () => paused,
  /** called whenever the track changes ("packId/ref", or '' when silent) */
  onChange(f: (id: string) => void) { listeners.push(f); },
  offChange(f: (id: string) => void) { const i = listeners.indexOf(f); if (i >= 0) listeners.splice(i, 1); },
  /** "packId/ref" of the track playing (or queued) */
  current: () => current,
  setVolume(v: number) { if (master) master.gain.value = v; },
  sfx(kind: 'tap' | 'mistake' | 'clear') {
    if (!settings.sfx || !sfxAc || sfxAc.state !== 'running' || !sfxGain) return;
    const o = sfxAc.createOscillator(), g = sfxAc.createGain(), t = sfxAc.currentTime;
    o.type = kind === 'mistake' ? 'sawtooth' : 'triangle';
    o.frequency.setValueAtTime(kind === 'mistake' ? 140 : kind === 'clear' ? 880 : 1320, t);
    if (kind === 'mistake') o.frequency.linearRampToValueAtTime(90, t + 0.25);
    g.gain.setValueAtTime(kind === 'tap' ? 0.25 : 0.6, t);
    g.gain.exponentialRampToValueAtTime(0.001, t + (kind === 'tap' ? 0.05 : 0.3));
    o.connect(g).connect(sfxGain);
    o.start(t);
    o.stop(t + 0.35);
  },
};
