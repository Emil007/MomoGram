// Pack building
// ———————————————————————————————————————————————————————————————————————
async function packFromEntries(entries: Entry[]): Promise<Pack> {
  const recs = await puzzleRecords(entries);
  if (!recs.length) throw new Error('NetWitch puzzle textures (puzzle_…) not found.');
  const byTheme = new Map<number, Puzzle[]>();
  let unthemed = 0;
  for (const r of recs) {
    const t = themeOf(r.id, r.w, r.h);
    if (!t) { unthemed++; continue; }
    if (!byTheme.has(t.theme)) byTheme.set(t.theme, []);
    byTheme.get(t.theme)!.push(r);
  }
  if (!byTheme.size) throw new Error('NetWitch: no puzzle belongs to a known theme.');

  const levels: PackLevel[] = [];
  for (const theme of [...byTheme.keys()].sort((a, b) => {
    const ia = THEMES.indexOf(a), ib2 = THEMES.indexOf(b);
    return (ia < 0 ? 99 : ia) - (ib2 < 0 ? 99 : ib2);
  })) {
    const ps = byTheme.get(theme)!;
    // split into normal (n) and gallery (g) groups within the theme
    const groups: Record<string, Puzzle[]> = {};
    for (const p of ps) {
      const gk = p.kind === 'n' ? 'n' : 'g';
      (groups[gk] = groups[gk] || []).push(p);
    }
    const title = (THEME_NAMES[theme] ?? `Theme ${theme}`);
    // level order: n first, then g; each sorted by id
    const order: Array<'n' | 'g'> = groups.n ? ['n'] : [];
    if (groups.g) order.push('g');
    let seq = 0;
    for (const gk of order) {
      const gps = groups[gk].sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));
      const puzzles: PackPuzzle[] = [];
      for (const p of gps) {
        const rows = await rowsOf(p);
        if (!rows.length) continue;
        puzzles.push({
          id: `${theme}-${gk}-${p.id}`,
          width: p.w,
          height: p.h,
          rows,
          name: { en: p.name.replace(/_/g, ' ') },
        });
      }
      if (!puzzles.length) continue;
      const groupTitle = gk === 'n' ? 'Normal' : 'Gallery';
      levels.push({
        id: `${theme}-${gk}-${++seq}`,
        title: { en: `${title}` },
        group: gk === 'n' ? `n-${theme}` : `g-${theme}`,
        groupTitle: { en: `${title} · ${groupTitle}` },
        rules: 'normal',
        puzzles,
      });
    }
  }

  const icon = findIcon(entries);
  return {
    format: 'momogram-pack', version: 1,
    id: 'netwitch',
    title: { en: 'NetWitch' },
    source: { game: 'NetWitch', platform: 'Android', developer: 'Studio Vogie', year: 2026, file: `${recs.length} puzzles` },
    levels,
    ...(icon ? { icon: { w: icon.icon.w, h: icon.icon.h, rgba: icon.icon.rgba } } : {}),
  };
}

