// Icon: the biggest launcher PNG decoded to RGBA.
// ———————————————————————————————————————————————————————————————————————
function findIcon(entries: Entry[]): { file: string; icon: ReturnType<typeof makeIcon> } | null {
  const pngs = entries.filter(e => /res\/mipmap[^/]*\/ic_launcher_foreground\.png$/i.test(e.name));
  pngs.sort((a, b) => b.data.length - a.data.length);
  const chosen = pngs[0] || entries.find(e => /res\/mipmap[^/]*\/ic_launcher[_a-z]*\.png$/i.test(e.name));
  if (!chosen) return null;
  const px = pngRgba(chosen.data);
  if (!px) return null;
  return { file: chosen.name, icon: makeIcon(px.w, px.h, new Uint8Array(px.rgba)) };
}

/** minimal PNG decoder (8-bit RGBA/RGB/grey, non-interlaced, multi-IDAT). */
function pngRgba(d: Uint8Array): { w: number; h: number; rgba: ArrayBuffer } | null {
  if (d.length < 33 || d[0] !== 0x89 || d[1] !== 0x50) return null;
  if (d[12] !== 0x49 || d[13] !== 0x48 || d[14] !== 0x44 || d[15] !== 0x52) return null;
  const w = (d[16] << 24) | (d[17] << 16) | (d[18] << 8) | d[19];
  const h = (d[20] << 24) | (d[21] << 16) | (d[22] << 8) | d[23];
  const depth = d[24], ctype = d[25];
  if (!(w >= 1 && w <= 1024 && h >= 1 && h <= 1024) || depth !== 8) return null;
  let bpp = 0;
  if (ctype === 6) bpp = 4; else if (ctype === 2) bpp = 3; else if (ctype === 0) bpp = 1; else return null;
  const idats: Uint8Array[] = [];
  let o = 8;
  while (o + 8 <= d.length) {
    const len = (d[o] << 24) | (d[o + 1] << 16) | (d[o + 2] << 8) | d[o + 3];
    const type = String.fromCharCode(d[o + 4], d[o + 5], d[o + 6], d[o + 7]);
    if (type === 'IEND') break;
    if (type === 'IDAT') idats.push(d.subarray(o + 8, o + 8 + len));
    o += 12 + len;
  }
  if (!idats.length) return null;
  let tl = 0; for (const id of idats) tl += id.length;
  const all = new Uint8Array(tl); let at = 0;
  for (const id of idats) { all.set(id, at); at += id.length; }
  let raw: Uint8Array;
  try { raw = unzlibSync(all); } catch { return null; }
  const stride = w * bpp; const want = (stride + 1) * h;
  if (raw.length < want) return null;
  const out = new Uint8Array(w * h * 4);
  const prev = new Uint8Array(stride), cur = new Uint8Array(stride);
  let p = 0;
  for (let y = 0; y < h; y++) {
    const filter = raw[p++];
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? cur[x - bpp] : 0;
      const b = prev[x], c = x >= bpp ? prev[x - bpp] : 0;
      const f = raw[p + x];
      cur[x] = filter === 0 ? f :
        filter === 1 ? (f + a) & 0xff :
        filter === 2 ? (f + b) & 0xff :
        filter === 3 ? (f + ((a + b) >> 1)) & 0xff :
        (f + paeth(a, b, c)) & 0xff;
    }
    p += stride;
    for (let x = 0; x < w; x++) {
      const ci = x * bpp, di = (y * w + x) * 4;
      if (ctype === 6) { out[di] = cur[ci]; out[di + 1] = cur[ci + 1]; out[di + 2] = cur[ci + 2]; out[di + 3] = cur[ci + 3]; }
      else if (ctype === 2) { out[di] = cur[ci]; out[di + 1] = cur[ci + 1]; out[di + 2] = cur[ci + 2]; out[di + 3] = 255; }
      else { const v = cur[ci]; out[di] = v; out[di + 1] = v; out[di + 2] = v; out[di + 3] = 255; }
    }
    prev.set(cur);
  }
  return { w, h, rgba: out.buffer };
}
function paeth(a: number, b: number, c: number) {
  const pp = a + b - c, pa = Math.abs(pp - a), pb = Math.abs(pp - b), pc = Math.abs(pp - c);
  return pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
}

// ———————————————————————————————————————————————————————————————————————
// unzip / recursive container unwrap
// ———————————————————————————————————————————————————————————————————————
function unzipAll(data: Uint8Array): Entry[] {
  const files = unzipSync(data);
  return Object.entries(files).filter(([n]) => !n.endsWith('/')).map(([name, d]) => ({ name, data: d as Uint8Array }));
}

/** true when the entries are a NetWitch container (manifest + puzzle marker). */
export async function looksLike(entries: Entry[]): Promise<boolean> {
  if (!hasManifestPackage(entries)) return false;
  const recs = await puzzleRecords(entries);
  // a valid set: several themes each with several puzzles
  const themes = new Set<number>();
  for (const r of recs) { const t = themeOf(r.id, r.w, r.h); if (t) themes.add(t.theme); }
  return themes.size >= 2 && recs.length >= 20;
}

/** recursively unwrap a container until the game's marker set is on top. */
export async function entriesOf(data: Uint8Array, depth = 0): Promise<Entry[]> {
  if (depth > 4) throw new Error('Too many nested containers.');
  let entries: Entry[];
  try { entries = unzipAll(data); } catch { return []; }
  if (hasManifestPackage(entries) && (await looksLike(entries))) return entries;
  const inner = entries.filter(e => /\.(apk|zip)$/i.test(e.name)).sort((a, b) => b.data.length - a.data.length)[0];
  if (inner) {
    const sub = await entriesOf(inner.data, depth + 1);
    if (sub.length && hasManifestPackage(sub) && (await looksLike(sub))) return sub;
  }
  return entries;
}

registerImporter({
  name: 'NetWitch (Android)',
  version: 1,
  async detect(data, fileName) {
    if (data.length < 4096) return false;
    try { return await looksLike(await entriesOf(data)); } catch { return false; }
  },
  async read(data, fileName) {
    const entries = await entriesOf(data);
    if (!(await looksLike(entries))) throw new Error('NetWitch puzzle textures not found.');
    const pack = await packFromEntries(entries);
    if (!pack.levels.length) throw new Error('NetWitch: no puzzles could be decoded.');
    return [pack];
  },
});

// folder/archive game (an extracted APK / XAPK, or the loose zip/apk file): same markers on loose files.
registerSetImporter({
  name: 'NetWitch (Android)',
  version: 1,
  find(names) {
    const roots = new Set<string>();
    let hasData = false;
    for (const n of names) {
      if (/^assets\/bin\/Data\/[0-9a-f]{32}$/.test(n)) { hasData = true; roots.add(n.slice(0, n.indexOf('assets/')) || '.'); }
    }
    if (hasData) roots.add('.');
    return [...roots];
  },
  async read(files: GameFiles, root: string) {
    const all: Entry[] = [];
    for (const n of files.names) {
      if (root !== '.' && !n.startsWith(root)) continue;
      const data = await files.get(n);
      if (!data) continue;
      if (/\.(apk|xapk|apkm|zip)$/i.test(n)) {
        try { all.push(...(await entriesOf(data))); } catch { /* skip unreadable */ }
      } else all.push({ name: root === '.' ? n : n.slice(root.length + 1), data });
    }
    if (!(await looksLike(all))) throw new Error('NetWitch puzzle textures not found.');
    const pack = await packFromEntries(all);
    if (!pack.levels.length) throw new Error('NetWitch: no puzzles could be decoded.');
    return [pack];
  },
});
