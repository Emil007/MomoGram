/** the theme (level) a puzzle belongs to, from its id: leading theme index then a size marker. */
const THEMES = [100, 101, 102, 103, 104, 105, 106, 9, 10, 11, 8, 7, 6, 5, 4, 3, 2, 1];
const SIZE_KEYS: Array<[string, number, number]> = [['25', 25, 25], ['20', 20, 20], ['15', 15, 15], ['10', 10, 10], ['05', 5, 5]];
const THEME_NAMES: Record<number, string> = {
  1: 'Building', 2: 'Vehicle', 3: 'House', 4: 'Nature', 5: 'People', 6: 'Animal',
  7: 'Object', 8: 'Food', 9: 'Fairy tale', 10: 'Middle Ages', 11: 'Sports',
  100: 'Abandoned Filming Studio', 101: 'Korea', 102: 'Japan', 103: 'America',
  104: 'Detective Novel', 105: 'Germany', 106: 'Oceania',
};
function themeOf(id: string, w: number, h: number): { theme: number; key: string } | null {
  for (const th of THEMES) {
    const ts = String(th);
    if (!id.startsWith(ts)) continue;
    const rest = id.slice(ts.length);
    for (const [mk, mw, mh] of SIZE_KEYS) {
      if (mw !== w || mh !== h) continue;
      if (!rest.startsWith(mk)) continue;
      if (!/^\d+$/.test(rest.slice(mk.length))) continue;
      return { theme: th, key: mk };
    }
    if (w === 20 && h === 20 && /^(?:60|604)/.test(rest) && /^\d+$/.test(rest.replace(/^(?:60|604)/, ''))) return { theme: th, key: '60' };
  }
  return null;
}

