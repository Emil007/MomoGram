// NetWitch (net.vogie.netwitch, Studio Vogie) — nonogram puzzles from its Unity (il2cpp)
// Android app. Importer + reverse-engineering, see ANALYSIS.md / VERIFIED.md.
//
// The game is a Unity 6000.6.8f1 il2cpp app (libil2cpp.so in the arm64 config split,
// `global-metadata.dat` in the base APK). There is no clue-table data anywhere — the game's
// whole shipped catalogue is a set of *solved picture textures*: ~2200 Texture2D among the
// hash-named serialized files under `assets/bin/Data/`, of which 379 are puzzle solutions
// named `puzzle_<id>@<W>x<H>_(n|g)#<english_name>`:
//
//   puzzle_7202001@20x20_n#bag          a 20×20 monochrome nonogram solution (the picture IS
//                                        the answer; black cell = filled)
//   puzzle_103604006@20x20_g#mt._rushmore6   a 20×20 "gallery" picture (same role: the grid of
//                                        the finished picture; solved by its own clues)
//
//   Field            Meaning
//   id               the puzzle's stable id, also its level/"theme" key below
//   @<W>x<H>_n       monochrome solution; W×H square (5/10/15/20/25)
//   @<W>x<H>_g       gallery picture; W×H square (15/20/25; the 20×20 "×60" six-variant blocks)
//   #<name>          the english subject name shown once solved
//
// The texture objects are Texture2D (class 28), Unity TextureFormat 50 = ASTC_RGBA_6x6,
// *inline* (their "complete image" is inside the serialized file, no .resS). Layout:
// m_Name, m_ForcedFallbackFormat(s32), m_DownscaleFallback(bool + pad), m_Width,
// m_Height, m_CompleteImageSize, m_MipCount, m_TextureFormat, …, then the image data
// (`m_CompleteImageSize` bytes at objectEnd − complete − 16; the trailing 16 bytes are the
// m_StreamData struct: u32 offset, u64 size, u32 path-len 0). We decode the ASTC stream
// with the embedded WASM decoder (base64, compiled from the texture2ddecoder Rust crate),
// reduced to a per-cell black/white mask: black (RGB 0,0,0) = filled, anything else empty
// (all 379 decode this way — see VERIFIED.md; the magenta corner is an ASTC void marker).
// Row/column clue runs are then derived from the filled mask (conserved sums: see VERIFIED.md).
//
//   Theme (level)      themes 1..11 are the "single-picture" worlds; 100..106 the
//                      gallery/hidden worlds. Each theme's puzzles cover 5×5 … 25×25
//                      plus the "×60" 20×20 four/four-picture blocks.
//
// Container-agnostic by design: detection never gates on the file extension (.apk / .xapk /
// .apkm / .zip / an extracted folder all work). The real markers that decide are
//   - the binary AndroidManifest.xml containing the UTF-16LE package name "net.vogie.netwitch"
//     (versionName "0.52.23"), and
//   - the puzzle marker: at least one serialized hash file under assets/bin/Data whose
//     Texture2D set contains a `puzzle_…@WxH_(n|g)#…` solution texture (and we can decode a
//     whole theme's worth of them to black/white grids).
//
// Icon: res/mipmap-xxxhdpi-v4/ic_launcher_foreground.png (192×192 launcher foreground over the
// background) → the biggest launcher PNG decoded to RGBA (also the XAPK's own icon.png).
