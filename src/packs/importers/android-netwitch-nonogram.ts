/** base64 → bytes, works in Node and browsers. */
function b64Bytes(b64: string): Uint8Array {
  const s = typeof atob !== 'undefined' ? atob(b64) : nodeAtob(b64);
  const out = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) out[i] = s.charCodeAt(i);
  return out;
}
function nodeAtob(b64: string): string {
  // Node's global atob exists since v16; fallback for odd environments
  const tbl = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  let o = ''; b64 = b64.replace(/=+$/, '');
  for (let i = 0; i < b64.length; i += 4) {
    const c0 = tbl.indexOf(b64[i]), c1 = tbl.indexOf(b64[i + 1]), c2 = tbl.indexOf(b64[i + 2]), c3 = tbl.indexOf(b64[i + 3]);
    const t = (c0 << 18) | (c1 << 12) | ((c2 < 0 ? 0 : c2) << 6) | (c3 < 0 ? 0 : c3);
    o += String.fromCharCode((t >> 16) & 255, (t >> 8) & 255, t & 255);
  }
  return o.slice(0, o.length - (b64.length % 4 === 2 ? 1 : b64.length % 4 === 3 ? 1 : 0));
}

let _astc: { decode(w: number, h: number, blockW: number, blockH: number, src: Uint8Array): Uint8Array } | null = null;
/** decode an ASTC block stream (RGBA8). Lazily instantiates the embedded wasm. */
async function astcRgba(w: number, h: number, blockW: number, blockH: number, src: Uint8Array): Promise<Uint8Array> {
  if (!_astc) {
    const mod = await WebAssembly.compile(b64Bytes(ASTC_WASM_B64) as BufferSource);
    const inst = await WebAssembly.instantiate(mod, {});
    const ex = inst.exports as any;
    const memory = ex.memory as WebAssembly.Memory;
    _astc = {
      decode(width: number, height: number, bw: number, bh: number, s: Uint8Array): Uint8Array {
        const srcPtr = ex.astc_alloc(s.length) as number;
        new Uint8Array(memory.buffer, srcPtr, s.length).set(s);
        const dstPixels = width * height;
        const dstPtr = ex.astc_alloc(dstPixels * 4) as number;
        ex.astc_decode(bw, bh, width, height, srcPtr, s.length, dstPtr, dstPixels);
        const out = new Uint8Array(memory.buffer, dstPtr, dstPixels * 4).slice();
        ex.astc_free();
        return out;
      },
    };
  }
  return _astc.decode(w, h, blockW, blockH, src);
}

