/** true when the entries carry the NetWitch manifest package. */
export function hasManifestPackage(entries: Entry[]): boolean {
  for (const e of entries) {
    if (!/^(AndroidManifest\.xml|META-INF\/?(manifest|.*manifest.*)\.xml)$/i.test(e.name)) continue;
    const d = e.data;
    const needle = new TextEncoder().encode('net.vogie.netwitch');
    for (let i = 0; i + needle.length * 2 <= d.length; i += 2) {
      let all = true;
      for (let k = 0; k < needle.length; k++) if (d[i + k * 2] !== needle[k] || d[i + k * 2 + 1] !== 0) { all = false; break; }
      if (all) return true;
    }
  }
  return false;
}

function objectNameOf(o: { classId: number; data: Uint8Array; le: boolean }): string | null {
  if (o.classId !== 28) return null;
  const d = o.data;
  const len = new DataView(d.buffer, d.byteOffset, d.byteLength).getUint32(0, o.le ?? true);
  if (!(len > 0 && len < 256 && 4 + len <= d.length)) return null;
  return new TextDecoder().decode(d.subarray(4, 4 + len));
}

/** Texture2D layout: (w, h, complete, format, payloadStart) or null. Payload is inline at the end. */
function textureLayout(o: { classId: number; data: Uint8Array }): { w: number; h: number; complete: number; format: number; payload: number } | null {
  const d = o.data;
  const nl = new DataView(d.buffer, d.byteOffset, d.byteLength).getUint32(0, true);
  if (!(nl > 0 && nl < 256 && 4 + nl <= d.length)) return null;
  // Unity Texture2D without a type tree: m_ForcedFallbackFormat(s32) then
  // m_Width, m_Height, m_CompleteImageSize, m_MipCount, m_TextureFormat. (Newer
  // builds add m_DownscaleFallback before width; this game does not — verified
  // on all 379 textures.) Try the plain A first and the padded B as a fallback.
  let p = (4 + nl + 3) & ~3;
  const rd = (q: number) => q + 24 <= d.length ? new DataView(d.buffer, d.byteOffset, d.byteLength).getUint32(q, true) : 0;
  const pa = p;
  const aW = rd(pa + 4), aH = rd(pa + 8), aComplete = rd(pa + 12), aFmt = rd(pa + 20);
  let pb = p + 5; pb = (pb + 3) & ~3;
  const bW = rd(pb), bH = rd(pb + 4), bComplete = rd(pb + 8), bFmt = rd(pb + 16);
  const plausible = (w: number, h: number, c: number) => w >= 1 && w <= 64 && h >= 1 && h <= 64 && c > 0 && c <= d.length;
  // the name's own grid size is authoritative; complete must match ceil(w/6)*ceil(h/6)*16
  const nm = new TextDecoder().decode(d.subarray(4, 4 + nl));
  const gm = nm.match(/@(\d+)x(\d+)_/);
  const want = gm ? Math.ceil(+gm[1] / 6) * Math.ceil(+gm[2] / 6) * 16 : 0;
  if (plausible(aW, aH, aComplete) && aFmt === 50 && (want === 0 || aComplete === want)) return { w: aW, h: aH, complete: aComplete, format: aFmt, payload: d.length - aComplete - 16 };
  if (plausible(bW, bH, bComplete) && bFmt === 50 && (want === 0 || bComplete === want)) return { w: bW, h: bH, complete: bComplete, format: bFmt, payload: d.length - bComplete - 16 };
  return null;
}

/** every puzzle Texture2D record in the entries: id, size, kind, name, object. */
export async function puzzleRecords(entries: Entry[]): Promise<Puzzle[]> {
  const out: Puzzle[] = [];
  const datas = entries.filter(e => /^assets\/bin\/Data\/[0-9a-f]{32}$/.test(e.name));
  for (const e of datas) {
    let objs: any[];
    try { objs = readSerialized(e.data); } catch { continue; }
    for (const o of objs) {
      if (o.classId !== 28) continue;
      const nm = objectNameOf(o);
      if (!nm) continue;
      const m = nm.match(/^puzzle_(.+?)@(\d+)x(\d+)_([ng])#(.+)$/);
      if (!m) continue;
      const lay = textureLayout(o);
      if (!lay) continue;
      if (lay.complete !== Math.ceil(+m[2] / 6) * Math.ceil(+m[3] / 6) * 16) continue; // must be ASTC 6×6 size
      if (lay.format !== 50) continue;                    // Unity ASTC_RGBA_6x6
      if (lay.payload < 0 || lay.payload + lay.complete > o.data.length) continue;
      out.push({ id: m[1], w: +m[2], h: +m[3], kind: m[4] as 'n' | 'g', name: m[5], blob: o.data.subarray(lay.payload, lay.payload + lay.complete) });
    }
  }
  return out;
}

interface Puzzle { id: string; w: number; h: number; kind: 'n' | 'g'; name: string; blob: Uint8Array }

/** decode a puzzle's texture to black/white rows ('#' filled). */
export async function rowsOf(r: Puzzle): Promise<string[]> {
  const rgba = await astcRgba(r.w, r.h, 6, 6, r.blob);
  const rows: string[] = [];
  for (let y = 0; y < r.h; y++) {
    let s = '';
    for (let x = 0; x < r.w; x++) {
      const o = (y * r.w + x) * 4;
      s += rgba[o] === 0 && rgba[o + 1] === 0 && rgba[o + 2] === 0 ? '#' : '.';
    }
    rows.push(s);
  }
  return rows;
}

